"""FastAPI + the same dashboard, served from one origin."""
import json
import os
from functools import lru_cache
from pathlib import Path
import joblib
import pandas as pd
from fastapi import FastAPI, HTTPException
from fastapi.responses import HTMLResponse, FileResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field
from .config import (CANCELLATION_DECISION_THRESHOLD, FEATURE_COLUMNS, HIGH_RISK_LOWER,
    LOW_RISK_UPPER, MODEL_PATH, MODEL_VERSION, PROJECT_ROOT)
from .schemas import BookingFeatures, PredictionResponse
from .explanation import explain

app=FastAPI(title='HotelMind AI API',version=MODEL_VERSION,
    description='Historical hotel cancellation research benchmark with local inference and SHAP.')


def get_model_path():
    return Path(os.environ.get('HOTELMIND_MODEL_PATH',str(MODEL_PATH)))


@lru_cache(maxsize=2)
def load_model(path):
    # Load only artifacts generated by trusted local code; joblib is executable.
    return joblib.load(path)


def require_model():
    path=get_model_path()
    if not path.is_file():
        raise HTTPException(status_code=503,detail='Model missing. Run scripts/train.py first.')
    return load_model(str(path))


def prediction_result(probability,model,explanation=None):
    level='Low' if probability<LOW_RISK_UPPER else ('Medium' if probability<HIGH_RISK_LOWER else 'High')
    return PredictionResponse(cancellation_probability=round(float(probability),6),
        predicted_cancellation=bool(probability>=CANCELLATION_DECISION_THRESHOLD),risk_level=level,
        model_name=getattr(model,'_hotelmind_name',None),explanation=explanation)


@app.get('/health')
def health():
    return {'status':'ok','model_available':get_model_path().is_file(),'model_version':MODEL_VERSION}


@app.get('/',response_class=HTMLResponse)
def dashboard():
    index=PROJECT_ROOT/'dist'/'index.html'
    if not index.is_file():
        raise HTTPException(status_code=503,detail='Dashboard files missing.')
    return HTMLResponse(index.read_text(encoding='utf-8').replace('data-runtime="browser"','data-runtime="api"'))


@app.get('/api/metrics')
def metrics():
    path=get_model_path().parent/'metrics.json'
    if not path.is_file():raise HTTPException(503,'Training report missing.')
    return json.loads(path.read_text(encoding='utf-8'))


@app.post('/predict',response_model=PredictionResponse)
def predict(booking:BookingFeatures,include_explanation:bool=True):
    model=require_model()
    frame=pd.DataFrame([booking.model_dump()])[FEATURE_COLUMNS]
    probability=float(model.predict_proba(frame)[0,1])
    explanation=explain(model,frame) if include_explanation else None
    return prediction_result(probability,model,explanation)


class BatchRequest(BaseModel):
    bookings:list[BookingFeatures]=Field(min_length=1,max_length=500)


@app.post('/predict/batch')
def predict_batch(batch:BatchRequest):
    model=require_model()
    frame=pd.DataFrame([b.model_dump() for b in batch.bookings])[FEATURE_COLUMNS]
    probabilities=model.predict_proba(frame)[:,1]
    return {'predictions':[prediction_result(float(p),model).model_dump() for p in probabilities]}


# Retraining reports always come from the currently selected artifact directory.
@app.get('/assets/metrics.json')
def live_metrics():
    return metrics()


@app.get('/assets/dataset_summary.json')
def dataset_summary():
    path=get_model_path().parent/'dataset_summary.json'
    if not path.is_file():raise HTTPException(404,'Dataset summary not found.')
    return FileResponse(path,media_type='application/json')


assets=PROJECT_ROOT/'dist'/'assets'
if assets.is_dir():
    app.mount('/assets',StaticFiles(directory=assets),name='assets')
